#!/usr/bin/env node
// Builds the court-notice workflow from the tested library.
//
//   node scripts/build-notices-workflow.mjs           write the file
//   node scripts/build-notices-workflow.mjs --check   fail if the file on disk is out of date
//
//   automations/notices/workflow.json   H&M Records: upload form -> vision model -> rules -> court_notices table -> one urgent alert
//
// The Code nodes hold the SAME functions the tests run (firm/lib/text.js, firm/lib/urgency.js and
// automations/notices/lib/notices.js) joined together, with the firm data and the prompt inlined as DATA.
// Only the few glue lines at the end of each node are written for n8n. To change a rule, change lib/ or the
// firm data files and rebuild. To change the prompt, change prompts/extract.md and rebuild.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) => path.join(root, ...p);
const readText = (...p) => fs.readFileSync(rel(...p), 'utf8').replace(/\r\n/g, '\n');
const require = createRequire(import.meta.url);
const { loadNoticeData, loadColumns } = require(rel('automations', 'notices', 'lib', 'data.js'));

// The one place the model is named. Change it here and rebuild.
export const VISION_MODEL = 'nvidia/nemotron-3.5-super-vl:free';

// Order matters: a file may only use names from the files above it. Every top-level name must be unique across them.
const LIB_FILES = ['firm/lib/text.js', 'firm/lib/urgency.js', 'automations/notices/lib/notices.js'];

function stripModuleSyntax(src, file) {
  const out = src
    .replace(/^'use strict';\n/m, '')
    .replace(/^const \{[^}]*\} = require\('[^']+'\);\n/gm, '')
    .replace(/^module\.exports = \{[^}]*\};\n?$/gm, '');
  if (/\brequire\(|module\.exports|\bexports\./.test(out)) throw new Error(file + ' still has module syntax after stripping');
  return out.trim() + '\n';
}
const libText = () => LIB_FILES.map((f) => '// ---- ' + f + ' ----\n' + stripModuleSyntax(readText(f), f)).join('\n');
const HEADER = [
  '// GENERATED by scripts/build-notices-workflow.mjs from the tested library in firm/lib and automations/notices/lib.',
  '// Do not edit here. Change the library, run the tests, rebuild.'
].join('\n');

const NOW_GLUE = `const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();\n`;

// n8n glue per node. $input, $ and this.helpers are provided by n8n. TEST_NOW and TEST_REF are variables only the parity test passes in.
const GLUE = {
  prepare: NOW_GLUE + `
const MODEL = ${JSON.stringify(VISION_MODEL)};
const today = noticeToday(NOW.getTime(), DATA.firm.timezone);
const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
let salt = '';
for (let i = 0; i < 4; i++) salt += ALPHABET[Math.floor(Math.random() * ALPHABET.length)];
if (typeof TEST_REF !== 'undefined' && TEST_REF) salt = TEST_REF;
const out = [];
const items = $input.all();
let seq = 0;
for (let i = 0; i < items.length; i++) {
  const binary = items[i].binary || {};
  for (const key of Object.keys(binary)) {
    const bin = binary[key];
    if (!/^image\\/(png|jpe?g)$/i.test(bin.mimeType || '')) continue;
    const buf = await this.helpers.getBinaryDataBuffer(i, key);
    const dataUrl = 'data:' + bin.mimeType + ';base64,' + buf.toString('base64');
    seq++;
    out.push({ json: { fileName: bin.fileName || key, ref: noticeMakeRef(today, salt, seq), today, now: NOW.toISOString(), requestBody: noticeRequestBody(MODEL, DATA.prompt, dataUrl) }, pairedItem: { item: i } });
  }
}
if (!out.length) throw new Error('No PNG or JPG image found in the upload');
return out;
`,
  read: `
const answers = $input.all();
const out = [];
for (let i = 0; i < answers.length; i++) {
  const c = $('Prepare images').itemMatching(i).json;
  const body = answers[i].json;
  const text = body && !body.error ? noticeModelText(body) : null;
  const r = noticeAssess(text, { today: c.today, now: c.now, ref: c.ref, fileName: c.fileName, model: c.requestBody.model, modelFailed: text === null }, DATA);
  out.push({ json: { row: r.row, result: { alert: r.alert, priority: r.priority, reasons: r.reasons, flags: r.flags, earliest: r.earliest, event: r.event } }, pairedItem: { item: i } });
}
return out;
`,
  alert: `
const saved = $input.all();
const read = $('Read and check').all();
const results = read.map((x, i) => {
  const s = saved[i] && saved[i].json;
  return Object.assign({}, x.json.result, { row: x.json.row, saved: !!(s && !s.error && s.id) });
});
const a = noticeAlert(results, DATA, read.length ? read[0].json.row.receivedAt : '');
if (!a) return [];
return [{ json: { subject: a.subject, text: a.text, count: a.count } }];
`
};

export function dataObject() { return loadNoticeData(); }
export function bundleCode(step) {
  return HEADER + '\nconst DATA = ' + JSON.stringify(dataObject()) + ';\n\n' + libText() + '\n// ---- n8n glue: the only part written for n8n. Everything above is the tested library. ----\n' + GLUE[step];
}

const ID = (n) => '00000000-0000-4000-8000-0000000004' + String(n).padStart(2, '0');
const COLUMNS = loadColumns();
const link = (to) => ({ node: to, type: 'main', index: 0 });
const codeAll = (id, name, pos, jsCode) => ({ id: ID(id), name, type: 'n8n-nodes-base.code', typeVersion: 2, position: pos, parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode } });
const TABLE = { __rl: true, mode: 'id', value: 'REPLACE_WITH_COURT_NOTICES_TABLE_ID' };

export function buildWorkflow() {
  const nodes = [
    {
      id: ID(1), name: 'Notice Upload Form', type: 'n8n-nodes-base.formTrigger', typeVersion: 2.6, position: [0, 0], webhookId: '3b8e6f1a-52d4-4c0e-9a77-0e1f3c9d2b40',
      parameters: {
        authentication: 'basicAuth',
        formTitle: 'Upload court notices',
        formDescription: 'Hollis & Marr LLP (fictional firm, invented documents only). PNG or JPG scans or photos. You can pick several at once. An automated assistant reads each one and saves what it read. Nothing is confirmed until an attorney confirms it. Do not upload real client papers.',
        formFields: { values: [{ fieldLabel: 'notice', fieldType: 'file', acceptFileTypes: '.png,.jpg,.jpeg', requiredField: true, multipleFiles: true }] },
        options: { appendAttribution: false, formSubmittedText: 'Thank you. Each notice is being read and saved with the status "Needs attorney confirmation". If a notice looks urgent, an attorney is alerted by email. This is not legal advice.' }
      },
      credentials: { httpBasicAuth: { name: 'Notice form login (attach your own)' } }
    },
    codeAll(2, 'Prepare images', [224, 0], bundleCode('prepare')),
    {
      id: ID(3), name: 'Ask vision model (OpenRouter)', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.5, position: [448, 0],
      parameters: { method: 'POST', url: 'https://openrouter.ai/api/v1/chat/completions', authentication: 'genericCredentialType', genericAuthType: 'httpCustomAuth', sendBody: true, specifyBody: 'json', jsonBody: '={{ $json.requestBody }}', options: {} },
      credentials: { httpCustomAuth: { name: 'OpenRouter (attach your own)' } },
      retryOnFail: true, maxTries: 3, waitBetweenTries: 5000, onError: 'continueRegularOutput'
    },
    codeAll(4, 'Read and check', [672, 0], bundleCode('read')),
    {
      id: ID(5), name: 'Save to court_notices', type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: [896, 0], onError: 'continueRegularOutput',
      parameters: {
        resource: 'row', operation: 'insert', dataTableId: TABLE,
        columns: {
          mappingMode: 'defineBelow',
          value: Object.fromEntries(COLUMNS.map((c) => [c.name, '={{ $json.row.' + c.name + ' }}'])),
          matchingColumns: [],
          schema: COLUMNS.map((c) => ({ id: c.name, displayName: c.name, required: false, defaultMatch: false, display: true, type: c.type === 'number' ? 'number' : 'string', readOnly: false, removed: false })),
          attemptToConvertTypes: false, convertFieldsToString: false
        },
        options: {}
      }
    },
    codeAll(6, 'Collect urgent alert', [1120, 0], bundleCode('alert')),
    {
      id: ID(7), name: 'Send urgent alert', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [1344, 0], onError: 'continueRegularOutput',
      parameters: {
        resource: 'message', operation: 'send', sendTo: 'REPLACE_WITH_ATTORNEY_ON_DUTY_ADDRESS', subject: '={{ $json.subject }}',
        emailType: 'text', message: '={{ $json.text }}', options: { appendAttribution: false }
      }
    },
    {
      id: ID(8), name: 'Notes', type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: [0, -260],
      parameters: {
        content: 'Court-notice reading for Hollis & Marr LLP (fictional). Upload scans or photos; a vision model copies what is printed into JSON; the tested rules (the Code nodes, generated from the library) decide the priority. Every row is saved with the status "Needs attorney confirmation": nothing here, and nothing a document says, can approve a notice. Only a person changes that cell.\nThe code never works out a deadline. It repeats a date as printed and counts days only to decide who looks first. A time limit counted from another event is copied as printed.\nUrgent (a summons or subpoena, a date within 7 days or already passed, a poor scan, a date that could not be read, or a failed read) sends ONE email per upload to the attorney on duty. The email has no party names. If the table row cannot be saved the email says so.\nThe upload form needs a basic-auth credential: notices are privileged. Execution data is not saved. Images go to a third-party model (see the README before using real papers). Not yet wired: the ops event and the daily digest line (Phase 7).',
        width: 1100, height: 240
      }
    }
  ];
  const connections = {
    'Notice Upload Form': { main: [[link('Prepare images')]] },
    'Prepare images': { main: [[link('Ask vision model (OpenRouter)')]] },
    'Ask vision model (OpenRouter)': { main: [[link('Read and check')]] },
    'Read and check': { main: [[link('Save to court_notices')]] },
    'Save to court_notices': { main: [[link('Collect urgent alert')]] },
    'Collect urgent alert': { main: [[link('Send urgent alert')]] }
  };
  return {
    name: 'H&M Records - Court notice reading',
    nodes,
    connections,
    settings: {
      executionOrder: 'v1',
      binaryMode: 'separate',
      // Notices hold names and case details. Keep them out of n8n's execution history.
      saveDataSuccessExecution: 'none',
      saveDataErrorExecution: 'none',
      saveExecutionProgress: false
    }
  };
}

const TARGET = 'automations/notices/workflow.json';
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(buildWorkflow(), null, 2) + '\n';
  const target = rel(TARGET);
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) { console.error(TARGET + ' is out of date. Run: node scripts/build-notices-workflow.mjs'); process.exit(1); }
    console.log('notices workflow file is up to date');
  } else {
    fs.writeFileSync(target, text);
    console.log('wrote ' + TARGET + ' (' + buildWorkflow().nodes.length + ' nodes, ' + text.length + ' characters)');
  }
}
