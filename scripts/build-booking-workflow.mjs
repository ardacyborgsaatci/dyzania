#!/usr/bin/env node
// Builds the booking workflow from the tested library.
//
//   node scripts/build-booking-workflow.mjs           write the file
//   node scripts/build-booking-workflow.mjs --check   fail if the file on disk is out of date
//
//   automations/booking/workflow.json   Dyzania Booking: POST booking/slots (free times) and POST booking/book (book one)
//
// The Code nodes hold the SAME functions the tests run (firm/lib/conflicts.js and automations/booking/lib/booking.js)
// joined together, with the firm data inlined as DATA. Only the few glue lines at the end of each node are written for
// n8n. To change a rule, change lib/ or the firm data files and rebuild.
import { createRequire } from 'node:module';
import { opsBuildNode, opsLogNode } from './lib/ops-nodes.mjs';
import { rel, libText as joinLibs, nodeIds, ifTrue, codeNodes, isMain, writeOrCheck } from './lib/workflow-kit.mjs';

const require = createRequire(import.meta.url);
const { loadBookingData, loadColumns } = require(rel('automations', 'booking', 'lib', 'data.js'));

// Order matters: a file may only use names from the files above it. Every top-level name must be unique across them.
const LIB_FILES = ['firm/lib/conflicts.js', 'automations/booking/lib/booking.js'];

const libText = () => joinLibs(LIB_FILES);
const HEADER = [
  '// GENERATED by scripts/build-booking-workflow.mjs from the tested library in firm/lib and automations/booking/lib.',
  '// Do not edit here. Change the library, run the tests, rebuild.'
].join('\n');

const NOW_GLUE = `const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();\n`;

// n8n glue per node. $input and $ are provided by n8n. TEST_NOW and TEST_REF are variables only the parity test passes in.
const GLUE = {
  slots: NOW_GLUE + `
const req = ($('Slots request').first().json.body) || {};
return [{ json: bookListSlots(req, bookRows($input.all()), NOW.getTime(), DATA) }];
`,
  decide: NOW_GLUE + `
const req = ($('Booking request').first().json.body) || {};
const ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
let ref = 'DY-';
for (let i = 0; i < 6; i++) ref += ALPHABET[Math.floor(Math.random() * ALPHABET.length)];
if (typeof TEST_REF !== 'undefined' && TEST_REF) ref = TEST_REF;
return [{ json: bookDecide(req, bookRows($input.all()), NOW.getTime(), DATA, { ref, now: NOW.toISOString() }) }];
`,
  verify: NOW_GLUE + `
const dec = $('Decide booking').first().json;
const inserted = $('Insert booking').first().json;
const rows = bookRows($input.all());
const v = bookVerify(inserted.id, rows, NOW.getTime(), DATA);
const json = { won: v.won, ref: dec.row.bookingRef, decision: dec };
if (!v.won) json.lost = bookRaceLost(dec.row, v.lost[inserted.id] || 'slot_taken', rows, NOW.getTime(), DATA);
return [{ json }];
`,
  confirmed: `
const res = $input.first().json;
const dec = $('Verify winner').first().json.decision;
const sent = !res.error && !!res.id;
return [{ json: { ref: dec.row.bookingRef, confirmation: sent ? 'sent' : 'failed', public: bookConfirmedPublic(dec.public, sent, DATA) } }];
`
};

// The ops event for one booking request, built from whichever way the run ended: booked, lost the slot, held, or refused.
// Invalid input and spam are not logged (the adapter returns nothing), so the chain simply ends. The booking row's leadRef
// makes this the receiving end of the intake -> booking handoff. Nothing here reads a name, an address or a phone number.
const OPS_GLUE = `
const dec = $('Decide booking').first().json;
let result = dec;
try { const v = $('Verify winner').first().json; if (v && v.won === false && v.lost) result = v.lost; } catch (e) { /* the slot was never inserted in this run */ }
const ref = (dec.row && dec.row.bookingRef) || '';
const leadRef = (result.row && result.row.leadRef) || (dec.row && dec.row.leadRef) || '';
const built = bookingEvent(result, { now: NOW, ref, leadRef });
if (!built) return [];
const ev = orFallback(built, { automation: 'booking', source: 'web', runId: leadRef || ref || 'unknown', summary: 'The ops event for a booking could not be built' }, NOW);
return [{ json: { row: toRow(ev.event) }, pairedItem: { item: 0 } }];
`;

export function dataObject() { return loadBookingData(); }
export function bundleCode(step) {
  return HEADER + '\nconst DATA = ' + JSON.stringify(dataObject()) + ';\n\n' + libText() + '\n// ---- n8n glue: the only part written for n8n. Everything above is the tested library. ----\n' + GLUE[step];
}

const ID = nodeIds('01');
const COLUMNS = loadColumns();
const link = (to) => ({ node: to, type: 'main', index: 0 });
const { codeAll } = codeNodes(ID);
const TABLE = { __rl: true, mode: 'id', value: 'REPLACE_WITH_BOOKINGS_TABLE_ID' };
const loadBookings = (id, name, pos) => ({
  id: ID(id), name, type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: pos, alwaysOutputData: true,
  // An empty table gives no item at all in n8n; alwaysOutputData gives one empty item so the chain keeps going. The library ignores it.
  parameters: { resource: 'row', operation: 'get', dataTableId: TABLE, returnAll: true, matchType: 'allConditions', filters: { conditions: [{ keyName: 'status', condition: 'eq', keyValue: 'booked' }] } }
});
const insertRow = (id, name, pos, from) => ({
  id: ID(id), name, type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: pos,
  parameters: {
    resource: 'row', operation: 'insert', dataTableId: TABLE,
    columns: {
      mappingMode: 'defineBelow',
      value: Object.fromEntries(COLUMNS.map((c) => [c.name, '={{ ' + from + '.row.' + c.name + ' }}'])),
      matchingColumns: [],
      schema: COLUMNS.map((c) => ({ id: c.name, displayName: c.name, required: false, defaultMatch: false, display: true, type: c.type === 'number' ? 'number' : 'string', readOnly: false, removed: false })),
      attemptToConvertTypes: false, convertFieldsToString: false
    },
    options: {}
  }
});
const updateRow = (id, name, pos, column, valueExpr, refExpr) => ({
  id: ID(id), name, type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: pos,
  parameters: {
    resource: 'row', operation: 'update', dataTableId: TABLE, matchType: 'allConditions',
    filters: { conditions: [{ keyName: 'bookingRef', condition: 'eq', keyValue: refExpr }] },
    columns: {
      mappingMode: 'defineBelow', value: { [column]: valueExpr }, matchingColumns: [],
      schema: [{ id: column, displayName: column, required: false, defaultMatch: false, display: true, type: 'string', readOnly: false, removed: false }],
      attemptToConvertTypes: false, convertFieldsToString: false
    },
    options: {}
  }
});
const reply = (id, name, pos, body) => ({ id: ID(id), name, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.4, position: pos, parameters: { respondWith: 'json', responseBody: body, options: {} } });
const webhook = (id, name, pos, pathName, webhookId) => ({
  id: ID(id), name, type: 'n8n-nodes-base.webhook', typeVersion: 2.1, position: pos, webhookId,
  parameters: { httpMethod: 'POST', path: pathName, authentication: 'headerAuth', responseMode: 'responseNode', options: {} }
});

export function buildWorkflow() {
  const nodes = [
    // ---- free times ----
    webhook(1, 'Slots request', [0, 0], 'booking/slots', '3b8e6f1a-52d4-4c0e-9a77-0e1f3c9d2b10'),
    loadBookings(2, 'Load bookings (slots)', [224, 0]),
    codeAll(3, 'List slots', [448, 0], bundleCode('slots')),
    reply(4, 'Reply with slots', [672, 0], '={{ $json }}'),
    // ---- book one ----
    webhook(5, 'Booking request', [0, 320], 'booking/book', '3b8e6f1a-52d4-4c0e-9a77-0e1f3c9d2b11'),
    loadBookings(6, 'Load bookings', [224, 320]),
    codeAll(7, 'Decide booking', [448, 320], bundleCode('decide')),
    { id: ID(8), name: 'Booked?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [672, 320], parameters: ifTrue("={{ $json.code === 'booked' }}") },
    insertRow(9, 'Insert booking', [896, 200], '$(\'Decide booking\').first().json'),
    loadBookings(10, 'Load bookings (verify)', [1120, 200]),
    codeAll(11, 'Verify winner', [1344, 200], bundleCode('verify')),
    { id: ID(12), name: 'Won the slot?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [1568, 200], parameters: ifTrue('={{ $json.won }}') },
    {
      id: ID(13), name: 'Send confirmation', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [1792, 100], onError: 'continueRegularOutput',
      parameters: {
        resource: 'message', operation: 'send', sendTo: '={{ $json.decision.row.email }}', subject: '={{ $json.decision.confirmation.subject }}',
        emailType: 'text', message: '={{ $json.decision.confirmation.text }}', options: { appendAttribution: false }
      }
    },
    codeAll(14, 'Confirmation outcome', [2016, 100], bundleCode('confirmed')),
    updateRow(15, 'Record confirmation status', [2240, 100], 'confirmation', "={{ $json.confirmation }}", "={{ $json.ref }}"),
    reply(16, 'Reply booked', [2464, 100], "={{ $('Confirmation outcome').first().json.public }}"),
    updateRow(17, 'Cancel losing row', [1792, 300], 'status', 'cancelled_race', "={{ $json.ref }}"),
    reply(18, 'Reply lost slot', [2016, 300], "={{ $('Verify winner').first().json.lost.public }}"),
    { id: ID(19), name: 'Held for review?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [896, 440], parameters: ifTrue("={{ $json.code === 'conflict_hold' }}") },
    insertRow(20, 'Insert held row', [1120, 400], '$(\'Decide booking\').first().json'),
    reply(21, 'Reply held', [1344, 400], "={{ $('Decide booking').first().json.public }}"),
    reply(22, 'Reply no booking', [1120, 560], '={{ $json.public }}'),
    // ---- ops event: written after the visitor has their answer, whichever way the run ended ----
    opsBuildNode({ id: ID(24), name: 'Build ops event', position: [2688, 320], generator: 'build-booking-workflow.mjs', glue: OPS_GLUE }),
    opsLogNode({ id: ID(25), name: 'Log ops event', position: [2912, 320] }),
    {
      id: ID(23), name: 'Notes', type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: [0, -200],
      parameters: {
        content: 'Booking for Dyzania LLP (fictional). POST booking/slots returns free times for an area. POST booking/book books one. Both need the header-auth credential; the website (or the voice line) calls them, never a browser directly.\nThe Code nodes are generated from the tested library. A booking is inserted, the table is read again and the row that came first (lowest row id) keeps the slot, so two people choosing the same time almost never both get it; see the README for the narrow case this does not cover. A person on a conflict hold gets a held row with no time and the same words as anyone else the system cannot book; they are never told why.\nThe only email is the fixed confirmation to the booked address. Execution data is not saved (names and emails). After the reply, one metadata-only ops event is logged (no name, address or phone). Not yet wired: the Google Calendar mirror.',
        width: 900, height: 230
      }
    }
  ];
  const connections = {
    'Slots request': { main: [[link('Load bookings (slots)')]] },
    'Load bookings (slots)': { main: [[link('List slots')]] },
    'List slots': { main: [[link('Reply with slots')]] },
    'Booking request': { main: [[link('Load bookings')]] },
    'Load bookings': { main: [[link('Decide booking')]] },
    'Decide booking': { main: [[link('Booked?')]] },
    'Booked?': { main: [[link('Insert booking')], [link('Held for review?')]] },
    'Insert booking': { main: [[link('Load bookings (verify)')]] },
    'Load bookings (verify)': { main: [[link('Verify winner')]] },
    'Verify winner': { main: [[link('Won the slot?')]] },
    'Won the slot?': { main: [[link('Send confirmation')], [link('Cancel losing row')]] },
    'Send confirmation': { main: [[link('Confirmation outcome')]] },
    'Confirmation outcome': { main: [[link('Record confirmation status')]] },
    'Record confirmation status': { main: [[link('Reply booked')]] },
    'Cancel losing row': { main: [[link('Reply lost slot')]] },
    'Reply booked': { main: [[link('Build ops event')]] },
    'Reply lost slot': { main: [[link('Build ops event')]] },
    'Reply held': { main: [[link('Build ops event')]] },
    'Reply no booking': { main: [[link('Build ops event')]] },
    'Build ops event': { main: [[link('Log ops event')]] },
    'Held for review?': { main: [[link('Insert held row')], [link('Reply no booking')]] },
    'Insert held row': { main: [[link('Reply held')]] }
  };
  return {
    name: 'Dyzania Booking - Slots and booking',
    nodes,
    connections,
    settings: {
      executionOrder: 'v1',
      // Bookings hold names and email addresses. Keep them out of n8n's execution history.
      saveDataSuccessExecution: 'none',
      saveDataErrorExecution: 'none',
      saveExecutionProgress: false
    }
  };
}

if (isMain(import.meta.url)) writeOrCheck([['automations/booking/workflow.json', buildWorkflow]], 'build-booking-workflow.mjs');
