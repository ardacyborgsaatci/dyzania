const TARGETS = [
  ['automations/triage/workflow-core.json', buildCoreWorkflow],
  ['automations/triage/workflow-gmail.json', buildGmailWorkflow]
];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let stale = false;
  for (const [file, build] of TARGETS) {
    const text = JSON.stringify(build(), null, 2) + '\n';
    const target = rel(file);
    if (process.argv.includes('--check')) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
      if (current !== text) { console.error(file + ' is out of date. Run: node scripts/build-triage-workflow.mjs'); stale = true; }
    } else {
      fs.writeFileSync(target, text);
      console.log('wrote ' + file + ' (' + build().nodes.length + ' nodes, ' + text.length + ' characters)');
    }
  }
  if (process.argv.includes('--check')) {
    if (stale) process.exit(1);
    console.log('triage workflow files are up to date');
  }
}
