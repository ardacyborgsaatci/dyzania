#!/usr/bin/env node
// Builds the two triage workflows from the tested library, the prompts and the knowledge base.
//
//   node scripts/build-triage-workflow.mjs           write both files
//   node scripts/build-triage-workflow.mjs --check   fail if either file on disk is out of date
//
//   automations/triage/workflow-core.json    Triage Core: screen -> classify (model) -> decide -> draft (model) -> finish
//   automations/triage/workflow-gmail.json   Triage Gmail: poll the +triage alias, run the core, create a DRAFT, label, alert
//
// The Code nodes hold the SAME functions the tests run (firm/lib/text.js, firm/lib/urgency.js,
// automations/triage/lib/triage.js) joined together, with the firm data inlined as DATA. Only the few glue lines
// at the end of each node are written for n8n. To change a rule, change lib/ or the data files and rebuild.
import { createRequire } from 'node:module';
import { opsBuildNode, opsLogNode } from './lib/ops-nodes.mjs';
import { rel, readText, readJson, libText, nodeIds, ifTrue, codeNodes, isMain, writeOrCheck } from './lib/workflow-kit.mjs';

const require = createRequire(import.meta.url);
const { loadTriageData } = require(rel('automations', 'triage', 'lib', 'data.js'));

// Order matters: a file may only use names from the files above it.
const LIB_FILES = ['firm/lib/text.js', 'firm/lib/urgency.js', 'automations/triage/lib/labels.js', 'automations/triage/lib/triage.js'];
const WRAPPER_FILES = ['automations/triage/lib/labels.js', 'automations/lib/brand-email.js'];

const HEADER = [
  '// GENERATED by scripts/build-triage-workflow.mjs from the tested library in firm/lib and automations/triage/lib.',
  '// Do not edit here. Change the library, run the tests, rebuild.'
].join('\n');

const NOW_GLUE = `
const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();
const TODAY = new Intl.DateTimeFormat('en-CA', { timeZone: DATA.firm.timezone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(NOW);
`;

// n8n glue per node. $input and $ are provided by n8n; TEST_NOW is a variable only the parity test passes in.
const GLUE = {
  screen: NOW_GLUE + `
const email = triageSanitize($input.item.json);
const screen = triageScreen(email, DATA, TODAY);
return { json: { email, screen, today: TODAY, startedAt: NOW.getTime() } };
`,
  decide: `
const prev = $('Screen email').item.json;
const model = triageNormalizeModel($input.item.json, DATA);
const decision = triageDecide(prev.email, prev.screen, model, DATA);
return { json: { email: prev.email, screen: prev.screen, model, decision, today: prev.today, startedAt: prev.startedAt, knowledge: triageKnowledgeFor(decision.category, DATA) } };
`,
  finish: `
const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();
const dec = $('Decide').item.json;
const draftRaw = dec.decision.draftMode === 'standard' ? $input.item.json : null;
const latencyMs = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? 0 : Date.now() - dec.startedAt;
return { json: triageFinish(dec, draftRaw, DATA, { now: NOW.toISOString(), latencyMs }) };
`
};

export function dataObject() { return loadTriageData(); }

export function bundleCode(step) {
  const data = 'const DATA = ' + JSON.stringify(dataObject()) + ';\n';
  return HEADER + '\n' + data + '\n' + libText(LIB_FILES) + '\n// ---- n8n glue: the only part written for n8n. Everything above is the tested library. ----' + GLUE[step];
}

// The Gmail wrapper only needs the Gmail and label helpers (lib/labels.js), not the firm data or the rules.
const WRAPPER_GLUE = {
  prepare: `
const cfg = { owner: 'YOUR_ADDRESS@gmail.com', alias: 'YOUR_ADDRESS+triage@gmail.com' };
return { json: triagePrepareGmail($input.item.json, cfg) };
`,
  combine: `
const r = $input.item.json;
const prep = $('Prepare email').all().map((i) => i.json).find((p) => p.messageId === r.messageId) || {};
return { json: triageCombine(r, prep) };
`,
  pick: `
return triagePickLabelIds($input.all().map((i) => i.json), $('Combine result').all().map((i) => i.json)).map((j) => ({ json: j }));
`,
  alerts: `
return $('Pick label IDs').all()
  .filter((i) => i.json.alertSend === true)
  .map((i) => ({ json: { alertSubject: i.json.alertSubject, alertText: i.json.alertText, alertHtml: brandEmailHtml(i.json.alertText, i.json.alertSubject) } }));
`,
  labels: `
return triageAllLabelNames().map((name) => ({ json: { name } }));
`
};

// The ops event for each email: what the triage decided, as a metadata-only row. It is built from the row just written to
// triage_log (no subject, no body, no sender address are in it). A row that cannot be turned into an event becomes an error
// row, so there is always one item per email and the labelling that follows is never starved.
const OPS_GLUE = `
return $input.all().map((item, i) => {
  const row = item.json || {};
  const built = orFallback(triageEvent(row, { now: NOW }), { automation: 'triage', source: 'gmail', runId: String(row.messageId || 'unknown'), summary: 'The ops event for an email could not be built' }, NOW);
  return { json: { row: toRow(built.event) }, pairedItem: { item: i } };
});
`;

export function wrapperCode(step) {
  return HEADER + '\n' + libText(WRAPPER_FILES) + '\n// ---- n8n glue ----' + WRAPPER_GLUE[step];
}

function stripLeadingComments(md) {
  return md.replace(/^(?:<!--[\s\S]*?-->\s*\n)+/, '').trim();
}

export function classifyPrompt() { return stripLeadingComments(readText('automations/triage/prompts/classify.md')); }
// The drafter's system prompt is the rules only. The knowledge for each email is sent in its user message (see Draft reply).
export function draftPrompt() { return stripLeadingComments(readText('automations/triage/prompts/draft.md')); }

const ID = nodeIds('00');
// Burst pacing lives in the caller (the Gmail workflow): it runs the core one email at a time with a Wait between them.
// The core has no pacing of its own. A first live run with 10 emails at once gave 4 model answers and 6 safe fallbacks,
// and the same 6 emails got real answers when run one at a time. The cause is inferred (provider rate or burst limits),
// not read from an error message. Groq free tier (checked in the console): each model 30 requests a minute, 1K a day,
// 8K tokens a minute, 200K tokens a day. A drafted email costs about 6.4K tokens on the drafter, so 8K a minute allows
// one drafted email about every 50 seconds. 60 seconds leaves margin. The daily 200K cap allows about 30 drafted emails a day.
const GMAIL_PACE_SECONDS = 60;
const COLUMNS = readJson('automations/triage/columns.json');
const link = (to) => ({ node: to, type: 'main', index: 0 });
const lmLink = (to) => ({ node: to, type: 'ai_languageModel', index: 0 });
const parserLink = (to) => ({ node: to, type: 'ai_outputParser', index: 0 });
const { code, codeAll } = codeNodes(ID);
const PRIVATE_SETTINGS = {
  executionOrder: 'v1',
  // The mail is personal and may be privileged. Keep it out of n8n's execution history.
  saveDataSuccessExecution: 'none',
  saveDataErrorExecution: 'none',
  saveExecutionProgress: false
};

export function buildCoreWorkflow() {
  const data = dataObject();
  const nodes = [
    {
      id: ID(1), name: 'Triage request', type: 'n8n-nodes-base.executeWorkflowTrigger', typeVersion: 1.3, position: [0, 224],
      parameters: { inputSource: 'workflowInputs', workflowInputs: { values: ['source', 'messageId', 'sampleId', 'from', 'subject', 'body'].map((name) => ({ name, type: 'string' })) } }
    },
    code(2, 'Screen email', [224, 224], bundleCode('screen')),
    {
      id: ID(3), name: 'Classify email', type: '@n8n/n8n-nodes-langchain.chainLlm', typeVersion: 1.9, position: [448, 224],
      parameters: {
        promptType: 'define',
        text: '=Today: {{ $json.today }}\n\n<email>\nFrom: {{ $json.email.fromName || "unknown sender" }} ({{ $json.email.fromDomain || "unknown domain" }})\nSubject: {{ $json.email.subject }}\n\n{{ $json.email.body }}\n</email>',
        hasOutputParser: true,
        messages: { messageValues: [{ type: 'SystemMessagePromptTemplate', message: classifyPrompt() }] }
      },
      retryOnFail: true, maxTries: 3, waitBetweenTries: 5000, onError: 'continueRegularOutput'
    },
    { id: ID(4), name: 'Classifier model', type: '@n8n/n8n-nodes-langchain.lmChatGroq', typeVersion: 1, position: [464, 448], parameters: { model: 'openai/gpt-oss-20b', options: { maxTokensToSample: 1500, temperature: 0 } } },
    {
      id: ID(5), name: 'Classification schema', type: '@n8n/n8n-nodes-langchain.outputParserStructured', typeVersion: 1.3, position: [592, 448],
      parameters: {
        schemaType: 'manual',
        inputSchema: {
          type: 'object',
          properties: {
            category: { type: 'string', enum: data.urgency.triageCategories },
            priority: { type: 'string', enum: ['urgent', 'high', 'normal', 'low'] },
            sentiment: { type: 'string', enum: ['positive', 'neutral', 'negative', 'angry'] },
            language: { type: 'string' }, summary: { type: 'string' }, needsHuman: { type: 'boolean' }, humanReason: { type: 'string' },
            confidence: { type: 'number' }, injectionSuspected: { type: 'boolean' }
          },
          required: ['category', 'priority', 'sentiment', 'language', 'summary', 'needsHuman', 'humanReason', 'confidence', 'injectionSuspected'],
          additionalProperties: false
        }
      }
    },
    code(6, 'Decide', [768, 224], bundleCode('decide')),
    { id: ID(7), name: 'Standard draft?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [992, 224], parameters: ifTrue("={{ $json.decision.draftMode === 'standard' }}") },
    {
      id: ID(8), name: 'Draft reply', type: '@n8n/n8n-nodes-langchain.chainLlm', typeVersion: 1.9, position: [1216, 112],
      parameters: {
        promptType: 'define',
        text: '=Greeting name: {{ $json.email.greetName }}\nDetected category: {{ $json.decision.category }}; priority: {{ $json.decision.priority }}; language: {{ $json.decision.language }}\n\n<email>\nSubject: {{ $json.email.subject }}\n\n{{ $json.email.body }}\n</email>\n\nKnowledge base for this reply:\n{{ $json.knowledge }}',
        hasOutputParser: true,
        messages: { messageValues: [{ type: 'SystemMessagePromptTemplate', message: draftPrompt() }] }
      },
      retryOnFail: true, maxTries: 3, waitBetweenTries: 5000, onError: 'continueRegularOutput'
    },
    { id: ID(9), name: 'Drafting model', type: '@n8n/n8n-nodes-langchain.lmChatGroq', typeVersion: 1, position: [1232, 336], parameters: { model: 'openai/gpt-oss-120b', options: { maxTokensToSample: 2500, temperature: 0.3 } } },
    {
      id: ID(10), name: 'Draft schema', type: '@n8n/n8n-nodes-langchain.outputParserStructured', typeVersion: 1.3, position: [1360, 336],
      parameters: {
        schemaType: 'manual',
        inputSchema: {
          type: 'object',
          properties: { reply: { type: 'string' }, kbArticlesUsed: { type: 'array', items: { type: 'string' } }, needsHuman: { type: 'boolean' }, confidence: { type: 'number' } },
          required: ['reply', 'kbArticlesUsed', 'needsHuman', 'confidence'], additionalProperties: false
        }
      }
    },
    code(11, 'Finish', [1440, 224], bundleCode('finish')),
    {
      id: ID(12), name: 'Notes', type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: [0, -120],
      parameters: {
        content: 'Triage Core for Dyzania LLP (fictional). Screen (rules) -> Classify (model) -> Decide (rules) -> Draft (model, only for ordinary mail) -> Finish (rules).\nThe Code nodes are generated from the tested library. The models give an opinion; the rules decide what happens and can only make handling more careful. Nothing here sends anything to the sender. Execution data is not saved because the mail may be privileged.',
        width: 760, height: 150
      }
    }
  ];
  const connections = {
    'Triage request': { main: [[link('Screen email')]] },
    'Screen email': { main: [[link('Classify email')]] },
    'Classify email': { main: [[link('Decide')]] },
    'Classifier model': { ai_languageModel: [[lmLink('Classify email')]] },
    'Classification schema': { ai_outputParser: [[parserLink('Classify email')]] },
    'Decide': { main: [[link('Standard draft?')]] },
    'Standard draft?': { main: [[link('Draft reply')], [link('Finish')]] },
    'Draft reply': { main: [[link('Finish')]] },
    'Drafting model': { ai_languageModel: [[lmLink('Draft reply')]] },
    'Draft schema': { ai_outputParser: [[parserLink('Draft reply')]] }
  };
  return { name: 'Dyzania Triage - Core', nodes, connections, settings: PRIVATE_SETTINGS };
}

export function buildGmailWorkflow() {
  const T = (type) => (type === 'number' ? 'number' : type === 'boolean' ? 'boolean' : 'string');
  const inputs = ['source', 'messageId', 'sampleId', 'from', 'subject', 'body'];
  const nodes = [
    {
      id: ID(1), name: 'New email', type: 'n8n-nodes-base.gmailTrigger', typeVersion: 1.4, position: [0, 0],
      parameters: {
        pollTimes: { item: [{ mode: 'everyMinute' }] }, simple: false, maxResults: 10,
        filters: { q: '(deliveredto:YOUR_ADDRESS+triage@gmail.com OR to:YOUR_ADDRESS+triage@gmail.com) -label:Triage-Processed', readStatus: 'both', includeSpamTrash: false, includeDrafts: false },
        options: { downloadAttachments: false }
      }
    },
    code(2, 'Prepare email', [224, 0], wrapperCode('prepare')),
    { id: ID(3), name: 'For triage alias?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [448, 0], parameters: ifTrue('={{ $json.forAlias }}') },
    {
      id: ID(4), name: 'Not seen before?', type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: [672, 0],
      parameters: {
        resource: 'row', operation: 'rowNotExists', dataTableId: { __rl: true, mode: 'id', value: 'REPLACE_WITH_TRIAGE_LOG_TABLE_ID' },
        matchType: 'allConditions', filters: { conditions: [{ keyName: 'messageId', keyValue: '={{ $json.messageId }}' }] }
      }
    },
    // One email at a time: the loop hands each new email to the core alone, the Wait paces the next one, and the loop's
    // done output hands every core result on to Combine result (which matches results to emails by messageId).
    { id: ID(21), name: 'One email at a time', type: 'n8n-nodes-base.splitInBatches', typeVersion: 3, position: [896, 0], parameters: { batchSize: 1, options: {} } },
    {
      id: ID(5), name: 'Run triage core', type: 'n8n-nodes-base.executeWorkflow', typeVersion: 1.4, position: [1120, -200],
      parameters: {
        source: 'database', workflowId: { __rl: true, mode: 'id', value: 'REPLACE_WITH_TRIAGE_CORE_WORKFLOW_ID', cachedResultName: 'Dyzania Triage - Core' },
        workflowInputs: {
          mappingMode: 'defineBelow',
          value: Object.fromEntries(inputs.map((n) => [n, '={{ $json.' + n + ' }}'])),
          matchingColumns: [],
          schema: inputs.map((n) => ({ id: n, displayName: n, required: false, defaultMatch: false, display: true, type: 'string', canBeUsedToMatch: true })),
          attemptToConvertTypes: false, convertFieldsToString: true
        },
        options: {}
      }
    },
    { id: ID(22), name: 'Pace between emails', type: 'n8n-nodes-base.wait', typeVersion: 1.1, position: [1344, -200], parameters: { resume: 'timeInterval', amount: GMAIL_PACE_SECONDS, unit: 'seconds' } },
    code(6, 'Combine result', [1120, 0], wrapperCode('combine')),
    { id: ID(7), name: 'Has draft?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [1344, -120], parameters: ifTrue('={{ $json.hasDraft }}') },
    {
      id: ID(8), name: 'Create draft', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [1568, -120],
      parameters: { resource: 'draft', operation: 'create', subject: '={{ $json.draftSubject }}', emailType: 'text', message: '={{ $json.draftReply }}', options: { threadId: '={{ $json.threadId }}', sendTo: '={{ $json.fromAddress }}' } }
    },
    {
      id: ID(9), name: 'Insert log row', type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: [1344, 120],
      parameters: {
        resource: 'row', operation: 'insert', dataTableId: { __rl: true, mode: 'id', value: 'REPLACE_WITH_TRIAGE_LOG_TABLE_ID' },
        columns: {
          mappingMode: 'defineBelow',
          value: Object.fromEntries(COLUMNS.map((c) => [c.name, '={{ $json.logRow.' + c.name + ' }}'])),
          matchingColumns: [],
          schema: COLUMNS.map((c) => ({ id: c.name, displayName: c.name, required: false, defaultMatch: false, display: true, type: T(c.type), readOnly: false, removed: false })),
          attemptToConvertTypes: false, convertFieldsToString: false
        },
        options: {}
      }
    },
    // The ops event is written right after the triage log row and before the labelling. Both nodes continue on failure.
    opsBuildNode({ id: ID(19), name: 'Build ops event', position: [1568, 120], generator: 'build-triage-workflow.mjs', glue: OPS_GLUE }),
    opsLogNode({ id: ID(20), name: 'Log ops event', position: [1792, 120] }),
    { id: ID(10), name: 'Get Gmail labels', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [2016, 120], parameters: { resource: 'label', operation: 'getAll', returnAll: true } },
    codeAll(11, 'Pick label IDs', [2240, 120], wrapperCode('pick')),
    { id: ID(12), name: 'Apply labels', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [2464, 120], parameters: { resource: 'message', operation: 'addLabels', messageId: '={{ $json.gmailId }}', labelIds: '={{ $json.labelIds }}' } },
    codeAll(13, 'Collect urgent alerts', [2688, 120], wrapperCode('alerts')),
    {
      id: ID(14), name: 'Email urgent alert', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [2912, 120],
      parameters: { resource: 'message', operation: 'send', sendTo: 'REPLACE_WITH_ATTORNEY_ON_DUTY_ADDRESS', subject: '={{ $json.alertSubject }}', emailType: 'html', message: '={{ $json.alertHtml }}', options: { appendAttribution: false } }
    },
    { id: ID(15), name: 'Create triage labels (run once)', type: 'n8n-nodes-base.manualTrigger', typeVersion: 1, position: [0, 360], parameters: {} },
    codeAll(16, 'Label names', [224, 360], wrapperCode('labels')),
    { id: ID(17), name: 'Create label', type: 'n8n-nodes-base.gmail', typeVersion: 2.2, position: [448, 360], parameters: { resource: 'label', operation: 'create', name: '={{ $json.name }}' } },
    {
      id: ID(18), name: 'Notes', type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position: [0, -240],
      parameters: {
        content: 'Gmail path for Dyzania Triage. Polls the +triage alias every minute, runs the Triage Core, then: creates a threaded Gmail DRAFT (only when the rules allow one; never sends), writes a metadata-only log row and one metadata-only ops event, applies Triage/* labels and, for urgent mail, emails an alert that has no message text. There is no node that sends to a sender. Run the manual branch below once to create the labels. Execution data is not saved.',
        width: 760, height: 170
      }
    }
  ];
  const connections = {
    'New email': { main: [[link('Prepare email')]] },
    'Prepare email': { main: [[link('For triage alias?')]] },
    'For triage alias?': { main: [[link('Not seen before?')]] },
    'Not seen before?': { main: [[link('One email at a time')]] },
    // splitInBatches: output 0 = done (all results), output 1 = the loop body (one email).
    'One email at a time': { main: [[link('Combine result')], [link('Run triage core')]] },
    'Run triage core': { main: [[link('Pace between emails')]] },
    'Pace between emails': { main: [[link('One email at a time')]] },
    'Combine result': { main: [[link('Has draft?'), link('Insert log row')]] },
    'Has draft?': { main: [[link('Create draft')]] },
    'Insert log row': { main: [[link('Build ops event')]] },
    'Build ops event': { main: [[link('Log ops event')]] },
    'Log ops event': { main: [[link('Get Gmail labels')]] },
    'Get Gmail labels': { main: [[link('Pick label IDs')]] },
    'Pick label IDs': { main: [[link('Apply labels')]] },
    'Apply labels': { main: [[link('Collect urgent alerts')]] },
    'Collect urgent alerts': { main: [[link('Email urgent alert')]] },
    'Create triage labels (run once)': { main: [[link('Label names')]] },
    'Label names': { main: [[link('Create label')]] }
  };
  return { name: 'Dyzania Triage - Gmail', nodes, connections, settings: PRIVATE_SETTINGS };
}

const TARGETS = [
  ['automations/triage/workflow-core.json', buildCoreWorkflow],
  ['automations/triage/workflow-gmail.json', buildGmailWorkflow]
];

if (isMain(import.meta.url)) writeOrCheck(TARGETS, 'build-triage-workflow.mjs');
