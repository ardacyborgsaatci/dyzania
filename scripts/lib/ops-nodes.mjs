// The two n8n nodes every workflow adds to write an ops event: a Code node that builds the row, and a data-table insert.
// The Code node holds automations/ops/lib/event.js and adapters.js as they are (the same files the tests run), plus a few
// glue lines written by the generator that uses it. The insert continues on failure: logging must never break a run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const readText = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8').replace(/\r\n/g, '\n');

export const OPS_TABLE_PLACEHOLDER = 'REPLACE_WITH_OPS_EVENTS_TABLE_ID';
export const OPS_FILES = ['automations/ops/lib/event.js', 'automations/ops/lib/adapters.js'];
// The scheduled jobs need the digest functions instead of the adapters.
export const OPS_JOB_FILES = ['automations/ops/lib/event.js', 'automations/ops/lib/digest.js'];
export const OPS_COLUMNS = JSON.parse(readText('automations/ops/ops_events.schema.json')).columns;

// The same time handling as the workflows' own glue. TEST_NOW exists only in the parity tests.
export const NOW_GLUE = "const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();\n";

function stripModuleSyntax(src, file) {
  const out = src
    .replace(/^'use strict';\n/m, '')
    .replace(/^const \{[^}]*\} = require\('[^']+'\);\n/gm, '')
    .replace(/^module\.exports = \{[^}]*\};\n?$/gm, '');
  if (/\brequire\(|module\.exports|\bexports\./.test(out)) throw new Error(file + ' still has module syntax after stripping');
  return out.trim() + '\n';
}

// `generator` is the script's file name, for the header comment only.
export function opsEventCode(generator, glue, files = OPS_FILES) {
  const header = [
    '// GENERATED by scripts/' + generator + ' from ' + files.join(' and ') + '.',
    '// Do not edit here. Change the library, run the tests, rebuild.'
  ].join('\n');
  const body = files.map((f) => '// ---- ' + f + ' ----\n' + stripModuleSyntax(readText(f), f)).join('\n');
  return header + '\n' + body + '\n// ---- n8n glue: the only part written for n8n. Everything above is the tested library. ----\n' + NOW_GLUE + glue;
}

// id: the full node id the caller's ID() makes.
export function opsBuildNode({ id, name, position, generator, glue, files }) {
  return { id, name, type: 'n8n-nodes-base.code', typeVersion: 2, position, parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: opsEventCode(generator, glue, files) } };
}

const nodeType = (col) => (col.type === 'number' ? 'number' : col.type === 'date' ? 'dateTime' : 'string');

export function opsLogNode({ id, name, position }) {
  return {
    id, name, type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position, onError: 'continueRegularOutput',
    parameters: {
      resource: 'row', operation: 'insert',
      dataTableId: { __rl: true, mode: 'id', value: OPS_TABLE_PLACEHOLDER },
      columns: {
        mappingMode: 'defineBelow',
        value: Object.fromEntries(OPS_COLUMNS.map((c) => [c.name, '={{ $json.row.' + c.name + ' }}'])),
        matchingColumns: [],
        schema: OPS_COLUMNS.map((c) => ({ id: c.name, displayName: c.name, required: false, defaultMatch: false, display: true, type: nodeType(c), readOnly: false, removed: false })),
        attemptToConvertTypes: false,
        convertFieldsToString: false
      },
      options: {}
    }
  };
}
