#!/usr/bin/env node
// Builds automations/intake/workflow.json from the tested library code.
//
//   node scripts/build-intake-workflow.mjs           write the workflow
//   node scripts/build-intake-workflow.mjs --check   fail if the file on disk is out of date
//
// The n8n Code node holds the SAME functions the tests run: firm/lib/*.js and automations/intake/lib/intake.js,
// concatenated, with the firm data inlined as a DATA constant. Nothing in the node is hand-written
// except the short glue at the end, so a change to the rules is made in lib/ and rebuilt here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { opsBuildNode, opsLogNode } from './lib/ops-nodes.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (...p) => path.join(root, ...p);
const readText = (...p) => fs.readFileSync(rel(...p), 'utf8').replace(/\r\n/g, '\n');
const readJson = (...p) => JSON.parse(readText(...p));

// Order matters: a file may only use names from the files above it.
const LIB_FILES = ['firm/lib/text.js', 'firm/lib/areas.js', 'firm/lib/conflicts.js', 'firm/lib/urgency.js', 'automations/intake/lib/intake.js'];

function stripModuleSyntax(src, file) {
  const out = src
    .replace(/^'use strict';\n/m, '')
    .replace(/^const \{[^}]*\} = require\('[^']+'\);\n/gm, '')
    .replace(/^module\.exports = \{[^}]*\};\n?$/gm, '');
  if (/\brequire\(|module\.exports|\bexports\./.test(out)) throw new Error(file + ' still has module syntax after stripping');
  return out.trim() + '\n';
}

function firmData() {
  const firm = readJson('firm/firm.json');
  return {
    firm: {
      name: firm.name, short: firm.short, domain: firm.domain, phone: firm.phone, timezone: firm.timezone,
      emails: firm.emails, officeHours: firm.officeHours, language: firm.language
    },
    areas: readJson('firm/practice-areas.json'),
    urgency: readJson('firm/urgency.json'),
    conflicts: readJson('firm/conflicts.json')
  };
}

const GLUE = `
// ---- n8n glue: the only part written for n8n. Everything above is the tested library. ----
// TEST_NOW is a variable the parity test passes in. It does not exist in n8n, and a visitor cannot set it.
const NOW = (typeof TEST_NOW !== 'undefined' && TEST_NOW) ? new Date(TEST_NOW) : new Date();
const TODAY = new Intl.DateTimeFormat('en-CA', { timeZone: DATA.firm.timezone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(NOW);
const results = [];
for (const item of $input.all()) {
  const raw = item.json || {};
  const body = raw.body && typeof raw.body === 'object' ? raw.body : raw;
  const ref = 'DY-' + TODAY.replace(/-/g, '').slice(2) + '-' + Math.random().toString(36).slice(2, 6).toUpperCase();
  results.push({ json: processIntake(body, DATA, { today: TODAY, ref, now: NOW.toISOString() }) });
}
return results;
`;

// The ops event for one lead: what the intake decided, as a metadata-only row (no name, address, phone or message text).
// A lead that reaches this node always has a lead object; if the event cannot be built, an error row says so.
const OPS_GLUE = `
const out = $('Validate and score').first().json;
const ref = String((out && out.lead && out.lead.ref) || 'unknown');
const built = orFallback(intakeEvent(out, { now: NOW }), { automation: 'intake', source: 'web', runId: ref, summary: 'The ops event for lead ' + ref + ' could not be built' }, NOW);
return [{ json: { row: toRow(built.event) }, pairedItem: { item: 0 } }];
`;

export function bundleCode() {
  const header = [
    '// GENERATED by scripts/build-intake-workflow.mjs from firm/lib/*.js and automations/intake/lib/intake.js.',
    '// Do not edit here. Change the library, run the tests, rebuild.',
    'const DATA = ' + JSON.stringify(firmData()) + ';',
    ''
  ].join('\n');
  const body = LIB_FILES.map((f) => '// ---- ' + f + ' ----\n' + stripModuleSyntax(readText(f), f)).join('\n');
  return header + '\n' + body + GLUE;
}

const ID = (n) => '00000000-0000-4000-8000-0000000000' + String(n).padStart(2, '0');
const COLUMNS = readJson('automations/intake/columns.json');
const REF = (name) => "={{ $('Validate and score').first().json." + name + ' }}';
const bool = (expr) => ({
  conditions: {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 1 },
    conditions: [{ id: 'c1', leftValue: expr, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
    combinator: 'and'
  },
  options: {}
});

export function buildWorkflow() {
  const nodes = [
    {
      id: ID(1), name: 'Intake form', type: 'n8n-nodes-base.webhook', typeVersion: 2.1, position: [0, 0], webhookId: '7c1d5f2e-0b7a-4c55-9f3e-1a2b3c4d5e61',
      parameters: { httpMethod: 'POST', path: 'intake', authentication: 'headerAuth', responseMode: 'responseNode', options: {} }
    },
    {
      id: ID(2), name: 'Validate and score', type: 'n8n-nodes-base.code', typeVersion: 2, position: [240, 0],
      parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: bundleCode() }
    },
    {
      id: ID(3), name: 'Valid?', type: 'n8n-nodes-base.if', typeVersion: 2, position: [480, 0],
      parameters: bool('={{ $json.ok === true && $json.spam !== true }}')
    },
    {
      id: ID(4), name: 'Save lead', type: 'n8n-nodes-base.dataTable', typeVersion: 1.1, position: [720, -100],
      parameters: {
        resource: 'row', operation: 'insert',
        dataTableId: { __rl: true, mode: 'id', value: 'REPLACE_WITH_INTAKE_LEADS_TABLE_ID' },
        columns: {
          mappingMode: 'defineBelow',
          value: Object.fromEntries(COLUMNS.map((c) => [c.name, '={{ $json.lead.' + c.name + ' }}'])),
          matchingColumns: [],
          schema: COLUMNS.map((c) => ({ id: c.name, displayName: c.name, required: false, defaultMatch: false, display: true, type: c.type === 'number' ? 'number' : 'string', readOnly: false, removed: false })),
          attemptToConvertTypes: false,
          convertFieldsToString: false
        },
        options: {}
      }
    },
    {
      id: ID(5), name: 'Reply to visitor', type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.4, position: [960, -100],
      parameters: {
        respondWith: 'json',
        responseBody: "={{ { ok: true, ref: $('Validate and score').first().json.lead.ref, nextStep: $('Validate and score').first().json.lead.nextStep, headline: $('Validate and score').first().json.visitor.headline, message: $('Validate and score').first().json.visitor.text } }}",
        options: {}
      }
    },
    // The ops event is written after the visitor has their answer and before the alert, so a failing alert mail cannot skip it.
    // The build node always returns one item (a failed build becomes an error row), and the insert continues on failure.
    opsBuildNode({ id: ID(11), name: 'Build ops event', position: [1200, -100], generator: 'build-intake-workflow.mjs', glue: OPS_GLUE }),
    opsLogNode({ id: ID(12), name: 'Log ops event', position: [1440, -100] }),
    {
      id: ID(6), name: 'Send alert?', type: 'n8n-nodes-base.if', typeVersion: 2, position: [1680, -100],
      parameters: bool("={{ $('Validate and score').first().json.alert.send === true }}")
    },
    {
      id: ID(7), name: 'Alert attorney on duty', type: 'n8n-nodes-base.gmail', typeVersion: 2.1, position: [1920, -200],
      parameters: {
        sendTo: 'REPLACE_WITH_ATTORNEY_ON_DUTY_ADDRESS',
        subject: REF('alert.subject'),
        emailType: 'text',
        message: REF('alert.text'),
        options: { appendAttribution: false }
      }
    },
    {
      id: ID(8), name: 'Spam?', type: 'n8n-nodes-base.if', typeVersion: 2, position: [720, 140],
      parameters: bool('={{ $json.spam === true }}')
    },
    {
      id: ID(9), name: 'Reply quietly', type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.4, position: [960, 60],
      parameters: { respondWith: 'json', responseBody: '={{ { ok: true } }}', options: {} }
    },
    {
      id: ID(10), name: 'Reply with errors', type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.4, position: [960, 220],
      parameters: { respondWith: 'json', responseBody: '={{ { ok: false, errors: $json.errors } }}', options: { responseCode: 422 } }
    }
  ];
  const link = (to) => ({ node: to, type: 'main', index: 0 });
  const connections = {
    'Intake form': { main: [[link('Validate and score')]] },
    'Validate and score': { main: [[link('Valid?')]] },
    'Valid?': { main: [[link('Save lead')], [link('Spam?')]] },
    'Save lead': { main: [[link('Reply to visitor')]] },
    'Reply to visitor': { main: [[link('Build ops event')]] },
    'Build ops event': { main: [[link('Log ops event')]] },
    'Log ops event': { main: [[link('Send alert?')]] },
    'Send alert?': { main: [[link('Alert attorney on duty')], []] },
    'Spam?': { main: [[link('Reply quietly')], [link('Reply with errors')]] }
  };
  return {
    name: 'Dyzania Intake - Lead intake and scoring',
    nodes,
    connections,
    settings: {
      executionOrder: 'v1',
      // The form text is personal and may be privileged. Keep it out of n8n's execution history.
      saveDataSuccessExecution: 'none',
      saveDataErrorExecution: 'none'
    }
  };
}

const target = rel('automations/intake/workflow.json');

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = JSON.stringify(buildWorkflow(), null, 2) + '\n';
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('automations/intake/workflow.json is out of date. Run: node scripts/build-intake-workflow.mjs');
      process.exit(1);
    }
    console.log('intake workflow.json is up to date');
  } else {
    fs.writeFileSync(target, text);
    const code = bundleCode();
    console.log('wrote automations/intake/workflow.json (' + buildWorkflow().nodes.length + ' nodes, Code node ' + code.length + ' characters)');
  }
}
