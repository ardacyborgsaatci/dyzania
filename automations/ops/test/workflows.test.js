// ---- all three ----
test('every workflow is safe to commit: placeholders only, no credentials, no secrets, no real mailbox, nothing kept in execution history', () => {
  const text = JSON.stringify(ALL);
  assert.deepEqual(Array.from(new Set(text.match(/REPLACE_WITH_[A-Z_]+/g))).sort(), ['REPLACE_WITH_OPS_EVENTS_TABLE_ID', 'REPLACE_WITH_TRIAGE_LOG_TABLE_ID', 'REPLACE_WITH_YOUR_EMAIL']);
  assert.doesNotMatch(text, /"credentials"/);
  assert.doesNotMatch(text, /gsk_|sk-[A-Za-z0-9]{10}|Bearer |password|AIza|xox[bp]-/i);
  assert.doesNotMatch(text, /wrenbook/i);
  assert.doesNotMatch(text.replace(/[A-Za-z0-9._-]+@[A-Za-z0-9.-]*example[A-Za-z.]*/g, ''), /@(gmail|outlook|yahoo|hotmail)\.com/i);
  for (const wf of ALL) {
    assert.ok(wf.name.startsWith('Dyzania Ops - '), wf.name);
    assert.equal(wf.settings.saveDataSuccessExecution, 'none');
    assert.equal(wf.settings.saveDataErrorExecution, 'none');
    assert.ok(!('active' in wf) || wf.active === false);
    assert.equal(wf.nodes.filter((n) => /httpRequest|langchain|lmChat|executeWorkflow/i.test(n.type)).length, 0, wf.name + ' makes no outside call and uses no model');
    for (const n of wf.nodes.filter((x) => x.type === 'n8n-nodes-base.gmail')) assert.equal(n.parameters.sendTo, 'REPLACE_WITH_YOUR_EMAIL', 'mail goes to the owner only');
    const names = new Set(wf.nodes.map((n) => n.name));
    for (const [from, outs] of Object.entries(wf.connections)) { assert.ok(names.has(from), from); outs.main.forEach((b) => b.forEach((l) => assert.ok(names.has(l.node), l.node))); }
    assert.equal(new Set(wf.nodes.map((n) => n.id)).size, wf.nodes.length, 'node ids are unique');
  }
  // the digest says what it is: counts and short summaries, and the only client email is the booking confirmation
  assert.match(D.buildDigest([], { now: NOW }).text, /fixed booking confirmation/);
});
