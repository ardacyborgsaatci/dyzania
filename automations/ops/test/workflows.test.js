'use strict';
// The three generated ops workflows: the Code nodes are run the way n8n would run them and compared with the library.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const root = path.join(__dirname, '..', '..', '..');
const dir = path.join(__dirname, '..', 'workflows');
const load = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const digestWf = load('daily-digest.json');
const alertWf = load('error-alert.json');
const cleanupWf = load('cleanup.json');
const ALL = [digestWf, alertWf, cleanupWf];
const node = (wf, name) => wf.nodes.find((n) => n.name === name);
const D = require('../lib/digest.js');
const E = require('../lib/event.js');
const A = require('../lib/adapters.js');
const schema = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'ops_events.schema.json'), 'utf8'));
const firm = JSON.parse(fs.readFileSync(path.join(root, 'firm', 'firm.json'), 'utf8'));

const NOW = new Date('2026-11-12T08:00:00Z');
const NOW_ISO = NOW.toISOString();
const run = (wf, name, items) => new Function('$input', 'TEST_NOW', node(wf, name).parameters.jsCode)({ all: () => items.map((json) => ({ json })), first: () => ({ json: items[0] }) }, NOW_ISO);
const next = (wf, name) => ((wf.connections[name] || { main: [] }).main[0] || []).map((l) => l.node);

test('the files on disk are what the build script makes', async () => {
  const mod = await import(pathToFileURL(path.join(root, 'scripts', 'build-ops-workflows.mjs')).href);
  for (const [file, build] of mod.TARGETS) assert.equal(fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n'), JSON.stringify(build(), null, 2) + '\n', file + ' is out of date: run node scripts/build-ops-workflows.mjs');
  assert.equal(mod.TARGETS.length, 3);
});

test('the Code nodes are the library plus a few glue lines, with no network, file or module access', () => {
  for (const wf of ALL) for (const n of wf.nodes.filter((x) => x.type === 'n8n-nodes-base.code')) {
    const c = n.parameters.jsCode;
    assert.match(c, /^\/\/ GENERATED by scripts\/build-ops-workflows\.mjs/, n.name);
    assert.doesNotMatch(c, /\brequire\(|module\.exports|\bimport\s|\bfetch\(|XMLHttpRequest|\bprocess\.|child_process|\beval\(|new Function/, n.name);
    assert.ok(c.includes('function buildEvent(') && c.includes('function retentionCutoff('), n.name + ' holds the library');
  }
});

// ---- daily digest ----
test('digest: 08:00 every day, reads ops_events, mails one summary to the owner address only', () => {
  const t = node(digestWf, 'Every morning');
  assert.equal(t.type, 'n8n-nodes-base.scheduleTrigger');
  assert.deepEqual(t.parameters.rule.interval, [{ field: 'days', daysInterval: 1, triggerAtHour: 8, triggerAtMinute: 0 }]);
  assert.equal(digestWf.settings.timezone, firm.timezone);
  assert.deepEqual(['Every morning', 'Get ops events', 'Build digest', 'Log ops event', 'Email digest to owner'], ['Every morning', ...['Get ops events', 'Build digest', 'Log ops event', 'Email digest to owner']]);
  assert.deepEqual(next(digestWf, 'Every morning'), ['Get ops events']);
  assert.deepEqual(next(digestWf, 'Get ops events'), ['Build digest']);
  assert.deepEqual(next(digestWf, 'Build digest'), ['Log ops event']);
  assert.deepEqual(next(digestWf, 'Log ops event'), ['Email digest to owner']);
  assert.equal(node(digestWf, 'Get ops events').alwaysOutputData, true, 'an empty table still produces a digest');
  const mail = digestWf.nodes.filter((n) => n.type === 'n8n-nodes-base.gmail');
  assert.equal(mail.length, 1);
  assert.equal(mail[0].parameters.sendTo, 'REPLACE_WITH_YOUR_EMAIL');
  assert.equal(mail[0].parameters.subject, "={{ $('Build digest').first().json.subject }}");
  assert.equal(mail[0].parameters.message, "={{ $('Build digest').first().json.text }}");
  assert.equal(mail[0].parameters.options.appendAttribution, false);
});

test('digest: the Code node gives what the library gives, from real events, and logs its own run', () => {
  const real = [];
  real.push(A.noticeEvent({ event: { ref: 'N-20261111-AB12-01', documentType: 'summons', priority: 'urgent', reasons: ['served_papers'], readStatus: 'ok' } }, { now: NOW }));
  real.push(A.bookingEvent({ event: { at: NOW_ISO, code: 'booked', reason: '', area: 'family', channel: 'voice', attorney: 'elena-voss' }, row: { bookingRef: 'DY-B00001' } }, { now: NOW, ref: 'DY-B00001' }));
  const rows = real.map((b, i) => E.toRow(Object.assign({}, b.event, { ts: new Date(NOW.getTime() - (i + 1) * 3600000) })));
  const out = run(digestWf, 'Build digest', rows.concat([{}]));
  assert.equal(out.length, 1);
  const want = D.buildDigest(rows, { now: NOW, firm: firm.name });
  assert.equal(out[0].json.subject, want.subject);
  assert.equal(out[0].json.text, want.text);
  assert.match(out[0].json.subject, /1 urgent court notice/);
  assert.match(out[0].json.text, /Consultations booked: 1 \(website 0, voice 1\)/);
  assert.deepEqual(Object.keys(out[0].json.row), schema.columns.map((c) => c.name));
  assert.equal(out[0].json.row.automation, 'ops');
  assert.equal(out[0].json.row.source, 'schedule');
  assert.equal(out[0].json.row.runId, 'digest-2026-11-12');
  assert.match(out[0].json.row.summary, /^Digest built: 2 events, 1 need a person$/);
  // an empty table (one empty item) and a missing table (no items) still give a digest
  for (const items of [[{}], []]) assert.match(run(digestWf, 'Build digest', items)[0].json.text, /0 events\./);
});

