test('error alert: the Code node gives what the library gives, strips any address and always yields a valid event row', () => {
  const failure = { workflow: { name: 'Dyzania Notices - Court notice reading' }, execution: { id: '77', url: 'https://n8n.example/execution/77', mode: 'trigger', lastNodeExecuted: 'Read and check', error: { message: 'Cannot read property of jane.doe@mail.example ' + 'y'.repeat(500) } } };
  const out = run(alertWf, 'Build alert', [failure]);
  const want = D.errorAlert(failure, { now: NOW, firm: firm.name });
  assert.equal(out[0].json.subject, want.subject);
  assert.equal(out[0].json.text, want.text);
  assert.ok(!out[0].json.text.includes('@'));
  assert.deepEqual(out[0].json.row, E.toRow(want.event.event));
  assert.equal(out[0].json.row.automation, 'notices');
  assert.equal(out[0].json.row.status, 'error');
  for (const odd of [{}, { workflow: { name: 'x@y.example' } }, { execution: { error: { message: null } } }]) {
    const row = run(alertWf, 'Build alert', [odd])[0].json.row;
    assert.equal(row.status, 'error');
    assert.ok(row.summary.length > 0 && !row.summary.includes('@'));
  }
});

// ---- cleanup ----
test('cleanup: 03:30, two tables on separate branches, delete nodes act only on selected ids', () => {
  const t = node(cleanupWf, 'Every night');
  assert.deepEqual(t.parameters.rule.interval, [{ field: 'days', daysInterval: 1, triggerAtHour: 3, triggerAtMinute: 30 }]);
  assert.deepEqual(next(cleanupWf, 'Every night').sort(), ['Get ops events', 'Get triage log']);
  assert.deepEqual([next(cleanupWf, 'Get ops events'), next(cleanupWf, 'Select expired events'), next(cleanupWf, 'Delete expired events')], [['Select expired events'], ['Delete expired events'], []]);
  assert.deepEqual([next(cleanupWf, 'Get triage log'), next(cleanupWf, 'Select expired triage rows'), next(cleanupWf, 'Delete expired triage rows')], [['Select expired triage rows'], ['Delete expired triage rows'], []]);
  const tables = {};
  for (const n of cleanupWf.nodes.filter((x) => x.type === 'n8n-nodes-base.dataTable')) {
    tables[n.parameters.dataTableId.value] = (tables[n.parameters.dataTableId.value] || 0) + 1;
    if (n.parameters.operation === 'deleteRows') {
      assert.deepEqual(n.parameters.filters.conditions, [{ keyName: 'id', condition: 'eq', keyValue: '={{ $json.id }}' }], n.name + ' deletes one row by id');
      assert.equal(n.parameters.matchType, 'allConditions');
    } else assert.equal(n.parameters.operation, 'get');
  }
  assert.deepEqual(tables, { REPLACE_WITH_OPS_EVENTS_TABLE_ID: 3 - 1, REPLACE_WITH_TRIAGE_LOG_TABLE_ID: 2 }, 'only these two tables are touched');
  assert.equal(cleanupWf.nodes.filter((n) => n.type === 'n8n-nodes-base.gmail').length, 0, 'cleanup sends nothing');
});

test('cleanup: the Code nodes select what the library selects, per table, and the table names are fixed in the code', () => {
  const day = (n) => new Date(NOW.getTime() - n * 86400000).toISOString();
  const events = [{ id: 1, ts: day(100) }, { id: 2, ts: day(10) }, { id: 3, ts: '' }, {}];
  const out = run(cleanupWf, 'Select expired events', events);
  assert.deepEqual(out.map((i) => i.json), [{ id: 1 }]);
  const triage = [{ id: 7, createdAt: day(91) }, { id: 8, createdAt: day(1) }];
  assert.deepEqual(run(cleanupWf, 'Select expired triage rows', triage).map((i) => i.json), [{ id: 7 }]);
  // nothing old: no items, so the delete node does not run
  assert.deepEqual(run(cleanupWf, 'Select expired events', [{ id: 2, ts: day(1) }]), []);
  assert.deepEqual(run(cleanupWf, 'Select expired events', [{}]), []);
  assert.match(node(cleanupWf, 'Select expired events').parameters.jsCode, /selectExpired\(.*"ops_events"/);
  assert.match(node(cleanupWf, 'Select expired triage rows').parameters.jsCode, /selectExpired\(.*"triage_log"/);
  // the only tables the code is ever asked about are the two with a rule; leads, bookings and notices are never selected
  const asked = [];
  for (const n of cleanupWf.nodes.filter((x) => x.type === 'n8n-nodes-base.code')) for (const m of n.parameters.jsCode.matchAll(/selectExpired\([^\n]*?, ("[a-z_]+"), NOW\)/g)) asked.push(JSON.parse(m[1]));
  assert.deepEqual(asked.sort(), ['ops_events', 'triage_log']);
  for (const table of ['intake_leads', 'bookings', 'court_notices']) assert.ok(!(table in D.RETENTION_DAYS), table);
});

